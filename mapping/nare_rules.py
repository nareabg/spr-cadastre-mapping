# 3 (14 Oct 2026) For those SPR house codes, any other cadastre object (garage,
#   shop, barn ...) is a conflict -> suggested, never mapped.
HOUSE_GROUP_OTHER_OBJECT_IS_CONFLICT = True

# 4 (14 Oct 2026) Street and avenue are the same main-street type (only 15 names
#   exist as both in one settlement). Lanes, dead ends, passages stay strict.
#   Never high confidence; similar spelling + street-vs-avenue is only suggested.
STREET_EQUALS_AVENUE = True

# 5 (14 Oct 2026) A Yerevan row that names its district is only ever mapped or
#   suggested inside that district. Found only in another district -> not_found
