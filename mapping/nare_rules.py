#   blank-name 'անցուղի'. An unnamed lane / dead end / passage written right after
#   the street type is read as that sub-street; it never matches the main street.
PASSAGE_AFTER_STREET_TYPE = True

# 2 (14 Oct 2026) A house and its land plot are one property: SPR house codes and
#   these cadastre types are compatible. Exact type wins; a compatible object is
#   mapped only when no exact one exists, and never with high confidence.
